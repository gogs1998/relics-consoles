def nes_chr_bank(font_fg='1', font_bg='2'):
    """8 KB: pattern table 0 (background) and pattern table 1 (sprites)."""
    bg = bytearray(0x1000)
    sp = bytearray(0x1000)
    for idx, rows in SCENE.items():
        bg[idx * 16:(idx + 1) * 16] = tile_from_rows(rows)
    for code in range(0x20, 0x60):
        bg[code * 16:(code + 1) * 16] = tile_from_rows(glyph_rows(chr(code), font_fg, font_bg))
    # 0x60..0x9F: the same font on a transparent background (colour 0)
    for code in range(0x20, 0x60):
        t = 0x40 + code
        bg[t * 16:(t + 1) * 16] = tile_from_rows(glyph_rows(chr(code), '1', '.'))
    for idx, rows in SPRITES.items():
        sp[idx * 16:(idx + 1) * 16] = tile_from_rows(rows)
    for code in range(0x20, 0x60):  # font in the sprite table too, transparent background
        sp[(0x40 + code) * 16:(0x41 + code) * 16] = tile_from_rows(glyph_rows(chr(code), '1', '.'))
    return bytes(bg + sp)
