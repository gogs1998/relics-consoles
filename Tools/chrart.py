def tile_from_rows(rows):
    """8 strings of 8 chars ('.', '1', '2', '3') -> 16 bytes of 2bpp planar CHR."""
    lo, hi = [], []
    for r in rows:
        a = b = 0
        for x, ch in enumerate(r):
            v = 0 if ch == '.' else int(ch)
            a |= (v & 1) << (7 - x)
            b |= ((v >> 1) & 1) << (7 - x)
        lo.append(a); hi.append(b)
    return bytes(lo + hi)


def glyph_rows(ch, fg='1', bg='2'):
    g = FONT.get(ch)
    rows = []
    for y in range(8):
        r = ''
        for x in range(8):
            on = g is not None and 0 <= y < 7 and 1 <= x <= 5 and g[y][x - 1] == '#'
            r += fg if on else bg
        rows.append(r)
    return rows


